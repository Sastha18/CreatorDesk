"""Shared PostgreSQL database layer for CreatorDesk."""
import streamlit as st
import psycopg

def connect_db():
    """Open a connection to the configured Supabase PostgreSQL database."""
    try:
        database_url = st.secrets["database"]["url"]
    except Exception as exc:
        raise RuntimeError(
            "Database URL not found. Configure [database].url in "
            ".streamlit/secrets.toml locally and in Streamlit Cloud Secrets."
        ) from exc

    return psycopg.connect(
        database_url,
        connect_timeout=10,
        sslmode="require",
    )


def initialize_database():
    """Create all CreatorDesk tables in PostgreSQL if they do not exist."""
    statements = [
        """
        CREATE TABLE IF NOT EXISTS clients (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            name TEXT NOT NULL,
            contact TEXT DEFAULT '',
            service TEXT DEFAULT '',
            created_at TEXT NOT NULL
        )
        """,
        """
        CREATE TABLE IF NOT EXISTS projects (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            client_id BIGINT NOT NULL REFERENCES clients(id),
            title TEXT NOT NULL,
            fee DOUBLE PRECISION DEFAULT 0,
            due_date TEXT NOT NULL,
            status TEXT DEFAULT 'Not started',
            payment_status TEXT DEFAULT 'Unpaid',
            created_at TEXT NOT NULL
        )
        """,
        """
        CREATE TABLE IF NOT EXISTS app_settings (
            setting_key TEXT PRIMARY KEY,
            setting_value TEXT NOT NULL DEFAULT ''
        )
        """,
        """
        CREATE TABLE IF NOT EXISTS payments (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            project_id BIGINT NOT NULL REFERENCES projects(id) ON DELETE RESTRICT,
            amount DOUBLE PRECISION NOT NULL CHECK (amount > 0),
            payment_date TEXT NOT NULL,
            method TEXT NOT NULL DEFAULT 'Other',
            note TEXT DEFAULT '',
            created_at TEXT NOT NULL
        )
        """,
        """
        CREATE TABLE IF NOT EXISTS expenses (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            title TEXT NOT NULL,
            amount DOUBLE PRECISION NOT NULL CHECK (amount > 0),
            expense_date TEXT NOT NULL,
            category TEXT NOT NULL DEFAULT 'Other',
            project_id BIGINT REFERENCES projects(id) ON DELETE RESTRICT,
            note TEXT DEFAULT '',
            created_at TEXT NOT NULL
        )
        """,
        """
        CREATE TABLE IF NOT EXISTS proposals (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            client_name TEXT NOT NULL,
            project_title TEXT NOT NULL,
            proposal_text TEXT NOT NULL,
            created_at TEXT NOT NULL,
            status TEXT NOT NULL DEFAULT 'Draft'
        )
        """,
        """
        INSERT INTO app_settings (setting_key, setting_value)
        VALUES ('business_name', '')
        ON CONFLICT (setting_key) DO NOTHING
        """,
    ]

    with connect_db() as conn:
        with conn.cursor() as cur:
            for statement in statements:
                cur.execute(statement)
